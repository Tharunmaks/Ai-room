class Voice:
    def __init__(self, style: TeacherStyle, rng: random.Random, student: str = "student"):
        self.s, self.rng, self.student = style, rng, student

    def _pick(self, bank: dict | list):
        pool = bank[self.s.tone] if isinstance(bank, dict) else bank
        return self.rng.choice(pool) if isinstance(pool, list) else pool

    def open(self, topic: str) -> str:
        return self._pick(_OPEN).format(student=self.student, topic=topic)

    def bridge(self) -> str:
        return self._pick(_BRIDGE)

    def praise(self) -> str:
        return self._pick(_PRAISE)

    def wrong(self) -> str:
        return self._pick(_WRONG)

    def close(self) -> str:
        return self._pick(_CLOSE)

    def jokes(self, n: int) -> list[str]:
        return self.rng.sample(_JOKES, min(n, len(_JOKES)))

    def encouragement(self) -> str:
        return self.rng.choice(_ENCOURAGE)
