"""Teacher behaviour as a handful of dials, plus the phrase banks that give each tone its voice.

Nothing here is generated by a model: a style is a set of parameters, and the
"voice" picks from hand-written lines with a seeded random generator, so the
same lesson is phrased the same way every time.
"""

from __future__ import annotations

import random
from dataclasses import asdict, dataclass, fields

TONES = ("warm", "neutral", "strict", "playful", "scholarly")
APPROACHES = ("explain", "socratic", "drill")


@dataclass
class TeacherStyle:
    name: str = "Ms. Patience"
    avatar: str = "🌱"
    tagline: str = "Warm, encouraging and extremely patient."
    tone: str = "warm"          # how the teacher speaks
    approach: str = "explain"   # explain first | pose problems first (Socratic) | short theory + lots of drills
    depth: int = 3              # 1-5: textbook readings and detail
    examples: int = 2           # 0-5 worked examples per concept
    practice: int = 3           # 0-10 practice problems at the end of a lesson
    hints: bool = True          # point at the 'watch out' notes
    praise: int = 2             # 0-3 how often encouragement appears
    humor: int = 1              # 0-3 jokes per lesson
    sources: bool = True        # cite where textbook passages come from

    def clamp(self) -> "TeacherStyle":
        self.tone = self.tone if self.tone in TONES else "warm"
        self.approach = self.approach if self.approach in APPROACHES else "explain"
        self.depth = max(1, min(5, int(self.depth)))
        self.examples = max(0, min(5, int(self.examples)))
        self.practice = max(0, min(10, int(self.practice)))
        self.praise = max(0, min(3, int(self.praise)))
        self.humor = max(0, min(3, int(self.humor)))
        self.hints, self.sources = bool(self.hints), bool(self.sources)
        return self

    def to_dict(self) -> dict:
        return asdict(self)


PRESETS: dict[str, TeacherStyle] = {
    "patient": TeacherStyle("Ms. Patience", "🌱", "Warm, encouraging, never in a hurry.", "warm", "explain", 3, 2, 3, True, 3, 1, True),
    "socratic": TeacherStyle("Professor Socrates", "🏛️", "Asks first, explains second — you do the thinking.", "scholarly", "socratic", 3, 1, 4, True, 1, 0, True),
    "strict": TeacherStyle("Dr. Rigor", "📐", "Precise, demanding, no shortcuts.", "strict", "explain", 4, 2, 5, False, 0, 0, True),
    "funny": TeacherStyle("Mr. Giggles", "🎈", "Jokes and stories — every fact still exact.", "playful", "explain", 2, 2, 3, True, 3, 3, True),
    "researcher": TeacherStyle("Dr. Curie", "🔬", "A working scientist: sources, evidence, depth.", "scholarly", "explain", 5, 2, 3, True, 1, 0, True),
    "drill": TeacherStyle("Coach Drill", "🏋️", "Short theory, then rep after rep.", "neutral", "drill", 2, 1, 8, True, 2, 1, False),
}
DEFAULT_PERSONA = "patient"


def style_from(persona: str | None, overrides: dict | None = None) -> TeacherStyle:
    """A preset, optionally with some dials changed (persona 'custom' starts from the default)."""
    base = PRESETS.get(persona or DEFAULT_PERSONA, PRESETS[DEFAULT_PERSONA])
    data = base.to_dict()
    names = {f.name for f in fields(TeacherStyle)}
    for k, v in (overrides or {}).items():
        if k in names and v is not None:
            data[k] = v
    if persona == "custom" and not (overrides or {}).get("name"):
        data["name"] = "Your teacher"
        data["avatar"] = (overrides or {}).get("avatar") or "🎓"
    return TeacherStyle(**data).clamp()


